/* Prints OpenDUNE's sound tables as Rust (crates/dune/src/tables/sound.rs).
 * Build: gcc -std=gnu99 -w -I<OpenDUNE>/include -I<OpenDUNE>/src gen_sound.c -o gen_sound */
#include <stdio.h>
#include "types.h"
#include "table/sound.c"

int main(void) {
	int i, j;
	int nm = sizeof(g_table_musics) / sizeof(g_table_musics[0]);
	int nv = sizeof(g_table_voiceMapping) / sizeof(g_table_voiceMapping[0]);
	int nf = sizeof(g_feedback) / sizeof(g_feedback[0]);
	printf("// @generated by tools/gen_tables/gen_sound.c from OpenDUNE's src/table/sound.c. Do not edit.\n\n");
	printf("/// g_table_voices: (filename pattern, priority). Prefixes: '+' = %%c house-independent,\n/// '%%' = house voice (prefix char), '-'/'/' = intro only, '?' = loaded on demand.\n");
	printf("pub static VOICES: [(&str, u16); %d] = [\n", NUM_VOICES);
	for (i = 0; i < NUM_VOICES; i++) printf("    (\"%s\", %u),\n", g_table_voices[i].string ? g_table_voices[i].string : "", g_table_voices[i].priority);
	printf("];\n\n/// g_table_musics: (file without extension, track index).\npub static MUSICS: [(&str, u16); %d] = [\n", nm);
	for (i = 0; i < nm; i++) printf("    (\"%s\", %u),\n", g_table_musics[i].string ? g_table_musics[i].string : "", g_table_musics[i].index);
	printf("];\n\n/// g_table_voiceMapping: voiceID -> index in VOICES (0xFFFF = AdLib sound effect only).\npub static VOICE_MAPPING: [u16; %d] = [", nv);
	for (i = 0; i < nv; i++) printf("%s%u,", i % 16 ? " " : "\n    ", g_table_voiceMapping[i]);
	printf("\n];\n\n/// g_feedback: (voice ids, message string id, AdLib sound id).\npub static FEEDBACK: [([u16; 5], u16, u16); %d] = [\n", nf);
	for (i = 0; i < nf; i++) {
		printf("    ([");
		for (j = 0; j < 5; j++) printf("%u, ", g_feedback[i].voiceId[j]);
		printf("], %u, %u),\n", g_feedback[i].messageId, g_feedback[i].soundId);
	}
	printf("];\n");
	return 0;
}
