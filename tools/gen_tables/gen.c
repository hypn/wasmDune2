/* Prints OpenDUNE's static game tables as Rust source (crates/dune/src/tables/generated.rs).
 * Build: gcc -I<OpenDUNE>/include -I<OpenDUNE>/src gen.c -o gen && ./gen > generated.rs */
#include <stdio.h>

#include "types.h"
#include "table/unitinfo.c"
#include "table/structureinfo.c"
#include "table/houseinfo.c"
#include "table/actioninfo.c"
#include "table/animation.c"
#include "table/explosion.c"
#include "table/tilediff.c"
#include "table/teamaction.c"
#include "table/movementtype.c"

static const char *b(int v) { return v ? "true" : "false"; }
static const char *s(const char *v) { return v ? v : ""; }

static void objectInfo(const ObjectInfo *o) {
	printf("        o: ObjectInfo {\n");
	printf("            string_id_abbrev: %u, name: \"%s\", string_id_full: %u, wsa: \"%s\",\n", o->stringID_abbrev, s(o->name), o->stringID_full, s(o->wsa));
	printf("            flags: ObjectInfoFlags { has_shadow: %s, factory: %s, not_on_concrete: %s, busy_state_is_incoming: %s, blur_tile: %s, has_turret: %s, conquerable: %s, can_be_picked_up: %s, no_message_on_death: %s, tab_selectable: %s, script_no_slowdown: %s, target_air: %s, priority: %s },\n",
		b(o->flags.hasShadow), b(o->flags.factory), b(o->flags.notOnConcrete), b(o->flags.busyStateIsIncoming), b(o->flags.blurTile), b(o->flags.hasTurret), b(o->flags.conquerable), b(o->flags.canBePickedUp), b(o->flags.noMessageOnDeath), b(o->flags.tabSelectable), b(o->flags.scriptNoSlowdown), b(o->flags.targetAir), b(o->flags.priority));
	printf("            spawn_chance: %u, hitpoints: %u, fog_uncover_radius: %u, sprite_id: %u, build_credits: %u, build_time: %u, available_campaign: %u,\n",
		o->spawnChance, o->hitpoints, o->fogUncoverRadius, o->spriteID, o->buildCredits, o->buildTime, o->availableCampaign);
	printf("            structures_required: 0x%08X, sort_priority: %u, upgrade_level_required: %u, actions_player: [%u, %u, %u, %u],\n",
		(unsigned)o->structuresRequired, o->sortPriority, o->upgradeLevelRequired, o->actionsPlayer[0], o->actionsPlayer[1], o->actionsPlayer[2], o->actionsPlayer[3]);
	printf("            available: %d, hint_string_id: %u, priority_build: %u, priority_target: %u, available_house: %u,\n",
		o->available, o->hintStringID, o->priorityBuild, o->priorityTarget, o->availableHouse);
	printf("        },\n");
}

static void anim(const char *name, const AnimationCommandStruct *a, int rows, int cols) {
	int i, j;
	printf("pub static %s: [[AnimationCmd; %d]; %d] = [\n", name, cols, rows);
	for (i = 0; i < rows; i++) {
		printf("    [");
		for (j = 0; j < cols; j++) printf("AnimationCmd(%u, %u), ", a[i * cols + j].command, a[i * cols + j].parameter);
		printf("],\n");
	}
	printf("];\n\n");
}

int main(void) {
	int i, j;
	printf("// @generated by tools/gen_tables/gen.c from OpenDUNE's src/table/*.c. Do not edit.\n");
	printf("#![allow(clippy::all)]\nuse super::types::*;\nuse crate::tile::Tile32;\n\n");

	printf("pub const ACTIONS_AI: [u16; 4] = [%u, %u, %u, %u];\n\n", g_table_actionsAI[0], g_table_actionsAI[1], g_table_actionsAI[2], g_table_actionsAI[3]);

	printf("pub const UNIT_INFO: [UnitInfo; %d] = [\n", UNIT_MAX);
	for (i = 0; i < UNIT_MAX; i++) {
		const UnitInfo *u = &g_table_unitInfo[i];
		printf("    UnitInfo { // %d\n", i);
		objectInfo(&u->o);
		printf("        index_start: %u, index_end: %u,\n", u->indexStart, u->indexEnd);
		printf("        flags: UnitInfoFlags { is_bullet: %s, explode_on_death: %s, sonic_protection: %s, can_wobble: %s, is_tracked: %s, is_ground_unit: %s, must_stay_in_map: %s, fires_twice: %s, impact_on_sand: %s, is_not_deviatable: %s, has_animation_set: %s, not_accurate: %s, is_normal_unit: %s },\n",
			b(u->flags.isBullet), b(u->flags.explodeOnDeath), b(u->flags.sonicProtection), b(u->flags.canWobble), b(u->flags.isTracked), b(u->flags.isGroundUnit), b(u->flags.mustStayInMap), b(u->flags.firesTwice), b(u->flags.impactOnSand), b(u->flags.isNotDeviatable), b(u->flags.hasAnimationSet), b(u->flags.notAccurate), b(u->flags.isNormalUnit));
		printf("        dimension: %u, movement_type: %u, animation_speed: %u, moving_speed_factor: %u, turning_speed: %u, ground_sprite_id: %u, turret_sprite_id: %u,\n",
			u->dimension, u->movementType, u->animationSpeed, u->movingSpeedFactor, u->turningSpeed, u->groundSpriteID, u->turretSpriteID);
		printf("        action_ai: %u, display_mode: %u, destroyed_sprite_id: %u, fire_delay: %u, fire_distance: %u, damage: %u, explosion_type: %u, bullet_type: %u, bullet_sound: %u,\n",
			u->actionAI, u->displayMode, u->destroyedSpriteID, u->fireDelay, u->fireDistance, u->damage, u->explosionType, u->bulletType, u->bulletSound);
		printf("    },\n");
	}
	printf("];\n\n");

	printf("pub const STRUCTURE_INFO: [StructureInfo; %d] = [\n", STRUCTURE_MAX);
	for (i = 0; i < STRUCTURE_MAX; i++) {
		const StructureInfo *si = &g_table_structureInfo[i];
		printf("    StructureInfo { // %d\n", i);
		objectInfo(&si->o);
		printf("        enter_filter: 0x%08X, credits_storage: %u, power_usage: %d, layout: %u, icon_group: %u,\n", (unsigned)si->enterFilter, si->creditsStorage, si->powerUsage, si->layout, si->iconGroup);
		printf("        animation_index: [%u, %u, %u], buildable_units: [", si->animationIndex[0], si->animationIndex[1], si->animationIndex[2]);
		for (j = 0; j < 8; j++) printf("%u, ", si->buildableUnits[j]);
		printf("], upgrade_campaign: [%u, %u, %u],\n    },\n", si->upgradeCampaign[0], si->upgradeCampaign[1], si->upgradeCampaign[2]);
	}
	printf("];\n\n");

	printf("pub static STRUCTURE_LAYOUT_TILES: [[u16; 9]; 7] = [\n");
	for (i = 0; i < 7; i++) { printf("    ["); for (j = 0; j < 9; j++) printf("%u, ", g_table_structure_layoutTiles[i][j]); printf("],\n"); }
	printf("];\npub static STRUCTURE_LAYOUT_EDGE_TILES: [[u16; 8]; 7] = [\n");
	for (i = 0; i < 7; i++) { printf("    ["); for (j = 0; j < 8; j++) printf("%u, ", g_table_structure_layoutEdgeTiles[i][j]); printf("],\n"); }
	printf("];\npub static STRUCTURE_LAYOUT_TILE_COUNT: [u16; 7] = [");
	for (i = 0; i < 7; i++) printf("%u, ", g_table_structure_layoutTileCount[i]);
	printf("];\npub static STRUCTURE_LAYOUT_TILE_DIFF: [Tile32; 7] = [");
	for (i = 0; i < 7; i++) printf("Tile32::new(%u, %u), ", g_table_structure_layoutTileDiff[i].x, g_table_structure_layoutTileDiff[i].y);
	printf("];\npub static STRUCTURE_LAYOUT_SIZE: [(u16, u16); 7] = [");
	for (i = 0; i < 7; i++) printf("(%u, %u), ", g_table_structure_layoutSize[i].width, g_table_structure_layoutSize[i].height);
	printf("];\npub static STRUCTURE_LAYOUT_TILES_AROUND: [[i16; 16]; 7] = [\n");
	for (i = 0; i < 7; i++) { printf("    ["); for (j = 0; j < 16; j++) printf("%d, ", g_table_structure_layoutTilesAround[i][j]); printf("],\n"); }
	printf("];\n\n");

	printf("pub static HOUSE_INFO: [HouseInfo; %d] = [\n", HOUSE_MAX);
	for (i = 0; i < HOUSE_MAX; i++) {
		const HouseInfo *h = &g_table_houseInfo[i];
		printf("    HouseInfo { name: \"%s\", toughness: %u, degrading_chance: %u, degrading_amount: %u, minimap_color: %u, special_count_down: %u, starport_delivery_time: %u, prefix_char: b'%c', special_weapon: %u, music_win: %u, music_lose: %u, music_briefing: %u, voice_filename: \"%s\" },\n",
			h->name, h->toughness, h->degradingChance, h->degradingAmount, h->minimapColor, h->specialCountDown, h->starportDeliveryTime, h->prefixChar, h->specialWeapon, h->musicWin, h->musicLose, h->musicBriefing, s(h->voiceFilename));
	}
	printf("];\n\n");

	printf("pub static ACTION_INFO: [ActionInfo; %d] = [\n", ACTION_MAX);
	for (i = 0; i < ACTION_MAX; i++) {
		const ActionInfo *a = &g_table_actionInfo[i];
		printf("    ActionInfo { string_id: %u, name: \"%s\", switch_type: %u, selection_type: %u, sound_id: %u },\n", a->stringID, a->name, a->switchType, a->selectionType, a->soundID);
	}
	printf("];\n\n");

	anim("ANIMATION_UNIT_MOVE", &g_table_animation_unitMove[0][0], 8, 8);
	anim("ANIMATION_UNIT_SCRIPT1", &g_table_animation_unitScript1[0][0], 4, 8);
	anim("ANIMATION_UNIT_SCRIPT2", &g_table_animation_unitScript2[0][0], 4, 8);
	anim("ANIMATION_MAP", &g_table_animation_map[0][0], 16, 8);
	anim("ANIMATION_STRUCTURE", &g_table_animation_structure[0][0], 29, 16);

	printf("pub static EXPLOSIONS: [&[ExplosionCmd]; %d] = [\n", EXPLOSIONTYPE_MAX);
	for (i = 0; i < EXPLOSIONTYPE_MAX; i++) {
		const ExplosionCommandStruct *e = g_table_explosion[i];
		printf("    &[");
		for (j = 0; ; j++) {
			printf("ExplosionCmd(%u, %u), ", e[j].command, e[j].parameter);
			if (e[j].command == EXPLOSION_STOP) break;
		}
		printf("],\n");
	}
	printf("];\n\n");

	printf("pub static MAP_DIFF: [i16; 4] = [%d, %d, %d, %d];\n", g_table_mapDiff[0], g_table_mapDiff[1], g_table_mapDiff[2], g_table_mapDiff[3]);
	printf("pub static TILE_DIFF: [[Tile32; 8]; 34] = [\n");
	for (i = 0; i < 34; i++) { printf("    ["); for (j = 0; j < 8; j++) printf("Tile32::new(%u, %u), ", g_table_tilediff[i][j].x, g_table_tilediff[i][j].y); printf("],\n"); }
	printf("];\n\n");

	printf("pub static TEAM_ACTION_NAME: [&str; %d] = [", TEAM_ACTION_MAX);
	for (i = 0; i < TEAM_ACTION_MAX; i++) printf("\"%s\", ", g_table_teamActionName[i]);
	printf("];\npub static MOVEMENT_TYPE_NAME: [&str; %d] = [", MOVEMENT_MAX);
	for (i = 0; i < MOVEMENT_MAX; i++) printf("\"%s\", ", g_table_movementTypeName[i]);
	printf("];\n");
	return 0;
}
