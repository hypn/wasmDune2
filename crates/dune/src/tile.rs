//! Tile coordinates. A `Tile32` is a fixed-point position (8.8 per axis, 64x64 tiles);
//! a "packed" tile is a 12-bit index `(y << 6) | x`.

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Tile32 {
    pub x: u16,
    pub y: u16,
}

pub const fn pack_xy(x: u16, y: u16) -> u16 {
    (y << 6) | x
}
pub const fn packed_x(p: u16) -> u16 {
    p & 0x3F
}
pub const fn packed_y(p: u16) -> u16 {
    (p >> 6) & 0x3F
}
pub const fn is_out_of_map(p: u16) -> bool {
    p & 0xF000 != 0
}

impl Tile32 {
    pub const fn new(x: u16, y: u16) -> Self {
        Tile32 { x, y }
    }
    pub fn is_valid(self) -> bool {
        ((self.x | self.y) & 0xC000) == 0
    }
    pub fn pos_x(self) -> u16 {
        (self.x >> 8) & 0x3F
    }
    pub fn pos_y(self) -> u16 {
        (self.y >> 8) & 0x3F
    }
    pub fn pack(self) -> u16 {
        (self.pos_y() << 6) | self.pos_x()
    }
    pub fn unpack(packed: u16) -> Self {
        Tile32 { x: ((packed & 0x3F) << 8) | 0x80, y: (((packed >> 6) & 0x3F) << 8) | 0x80 }
    }
    pub fn make_xy(x: u16, y: u16) -> Self {
        Tile32 { x: x << 8, y: y << 8 }
    }
    pub fn center(self) -> Self {
        Tile32 { x: (self.x & 0xFF00) | 0x80, y: (self.y & 0xFF00) | 0x80 }
    }
}

/// Tile_MoveByRandom
pub fn move_by_random(rng: &mut crate::rng::Rng, tile: Tile32, distance: u16, center: bool) -> Tile32 {
    if distance == 0 {
        return tile;
    }
    let mut x = tile.x;
    let mut y = tile.y;
    let mut new_distance = rng.random_256() as u16;
    while new_distance > distance {
        new_distance /= 2;
    }
    let distance = new_distance as i32;
    let orientation = rng.random_256() as usize;
    x = x.wrapping_add((((STEPX[orientation] as i32 * distance) / 128) * 16) as u16);
    y = y.wrapping_sub((((STEPY[orientation] as i32 * distance) / 128) * 16) as u16);
    if x > 16384 || y > 16384 {
        return tile;
    }
    let ret = Tile32 { x, y };
    if center { ret.center() } else { ret }
}

